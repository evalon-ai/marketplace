#!/usr/bin/env node
/**
 * Set every plugin build version to the given semver and verify the shipped
 * payload is intact.
 * Usage: node pin.mjs <version>
 * Does not prompt — caller must confirm before running.
 *
 * Hook commands carry no package version: `hooks.json` invokes
 * `node dist/launcher.mjs` via the runner plugin-root variable, and runtime
 * bumps ride the payload. Only plugin manifests, the payload `package.json`,
 * and the README's `npx … configure` examples name one.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../../..");
const pkgRe = /@ev-ai\/agent-hook@\d+\.\d+\.\d+/g;
const semver = /^\d+\.\d+\.\d+$/;

const [, , version] = process.argv;
if (!semver.test(version || "")) {
  console.error("Usage: node pin.mjs <version>");
  process.exit(1);
}

const pin = `@ev-ai/agent-hook${version ? `@${version}` : ""}`;

const PLUGIN_DIRS = ["plugins/claude", "plugins/cursor", "plugins/codex"];

const PLUGIN_MANIFESTS = [
  "plugins/claude/.claude-plugin/plugin.json",
  "plugins/cursor/.cursor-plugin/plugin.json",
  "plugins/codex/.codex-plugin/plugin.json",
];

/** Every runner publishes the plugin under one name; the dir names the runner. */
const PLUGIN_NAME = "ev-ai-agent-hooks";

/** Generated by `sync:hooks` in the monorepo — must exist before a release. */
const PAYLOAD_FILES = ["dist/launcher.mjs", "dist/launcher-update.mjs", "dist/hook.mjs", "package.json"];

/** Hook entry every `hooks.json` command invokes. */
const HOOK_ENTRY = "dist/launcher.mjs";

/** Retired payload from earlier delivery shapes; `sync:hooks` does not delete it. */
const RETIRED_PAYLOAD_FILES = ["launcher.sh", "launcher.ps1", "hook.mjs", "version", "SHA256SUMS"];

const problems = [];

for (const dir of PLUGIN_DIRS) {
  for (const file of PAYLOAD_FILES) {
    const rel = path.join(dir, file);
    if (!fs.existsSync(path.join(root, rel))) {
      problems.push(`Missing payload: ${rel} — run \`sync:hooks\` from the monorepo first`);
    }
  }

  for (const file of RETIRED_PAYLOAD_FILES) {
    const rel = path.join(dir, file);
    if (fs.existsSync(path.join(root, rel))) {
      problems.push(`Retired payload still present: ${rel} — remove it (hooks now run node ${HOOK_ENTRY})`);
    }
  }

  // Payload version must equal the manifest pin so a bump cannot ship mixed bytes.
  const pkgRel = path.join(dir, "package.json");
  const pkgAbs = path.join(root, pkgRel);
  if (fs.existsSync(pkgAbs)) {
    const shipped = JSON.parse(fs.readFileSync(pkgAbs, "utf8")).version;
    if (shipped !== version) {
      problems.push(
        `${pkgRel} says ${shipped}, not ${version} — re-run \`sync:hooks\` from a monorepo at ${version}`,
      );
    }
  }

  const hooksRel = path.join(dir, "hooks/hooks.json");
  const hooks = fs.readFileSync(path.join(root, hooksRel), "utf8");
  if (hooks.includes("npx")) {
    problems.push(`${hooksRel} still wires npx — run \`sync:hooks\` from the monorepo first`);
  }
  if (!hooks.includes(HOOK_ENTRY)) {
    problems.push(`${hooksRel} does not invoke ${HOOK_ENTRY} — run \`sync:hooks\` from the monorepo first`);
  }
}

if (problems.length > 0) {
  for (const problem of problems) {
    console.error(problem);
  }
  process.exit(1);
}

let changed = 0;

for (const rel of PLUGIN_MANIFESTS) {
  const abs = path.join(root, rel);
  const json = JSON.parse(fs.readFileSync(abs, "utf8"));
  if (json.name !== PLUGIN_NAME) {
    console.error(`${rel} name is "${json.name}", expected "${PLUGIN_NAME}"`);
    process.exit(1);
  }
  const old = json.version;
  json.version = version;
  fs.writeFileSync(abs, `${JSON.stringify(json, null, 2)}\n`);
  changed += 1;
  console.log(`updated ${rel}: ${old} → ${version}`);
}

// README only documents `npx … configure` / `migrate-to-plugin` — not hook commands.
const readmeAbs = path.join(root, "README.md");
const before = fs.readFileSync(readmeAbs, "utf8");
const after = before.replace(pkgRe, pin);
if (after === before) {
  console.log("Unchanged: README.md");
} else {
  fs.writeFileSync(readmeAbs, after);
  changed += 1;
  console.log("updated README.md");
}

console.log(`done: plugin version ${version}, payload verified (${changed} files)`);
